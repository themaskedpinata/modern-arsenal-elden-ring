"""C3 (docs/C3_DESIGN.md 1.1): generates mod/mw2er-core/src/collision_layers_rows.in (the array literal of
`collision_layers::DEFAULT_ROWS`) from tools/scripts/fixtures/c3_layers.json (the emu2.py output, read-only).

  python -I tools/scripts/c3_layers_rs.py          writes the .in file
  python -I tools/scripts/c3_layers_rs.py --check  PASS when the .in file equals the fixture's rows
"""
import hashlib
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parents[2]
fx = root / 'tools' / 'scripts' / 'fixtures' / 'c3_layers.json'
out = root / 'mod' / 'mw2er-core' / 'src' / 'collision_layers_rows.in'
T = json.loads(fx.read_text())
rows = []
for a in range(128):
    v = 0
    for b in range(128):
        if T[a][b]:
            v |= 1 << b
    rows.append(v)
sha = hashlib.sha256(fx.read_bytes()).hexdigest()
text = '// generated by tools/scripts/c3_layers_rs.py from fixtures/c3_layers.json sha256 %s\n[\n' % sha
text += ''.join('    ' + ' '.join('0x%032x,' % rows[j] for j in (i, i + 1)) + '\n' for i in range(0, 128, 2))
text += ']\n'
if '--check' in sys.argv:
    cur = out.read_text() if out.exists() else ''
    ok = cur.replace('\r\n', '\n') == text
    print(('PASS' if ok else 'FAIL') + ' collision_layers_rows.in == c3_layers.json rows (sha %s)' % sha[:12])
    sys.exit(0 if ok else 1)
out.write_text(text, newline='\n')
print('wrote', out.name, 'sha', sha[:12])
