"""Writes mod/regbuild/src/fields_gen.rs: the field offsets regbuild needs (docs/INSTALLER_DESIGN.md P2).

Usage: python -I gen_regbuild_fields.py [--check]
Source: WitchyBND's Paramdex ER defs (param_rows.load_def, fields active at regulation 11730034). Only the facts are
written (name, type, byte offset, bit offset/width) for the fields build_regulation.py overrides or asserts, plus the
3 AssetEnvironmentGeometryParam fields of the object-break check; no Paramdex file is shipped. --check compares the
existing file with a fresh generation (exit 1 when it differs). Dev tool only: the installer never runs it.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import build_regulation as br  # noqa: E402
import param_rows  # noqa: E402

OUT = br.ROOT / "mod" / "regbuild" / "src" / "fields_gen.rs"
TYPES = {"Bullet": "BULLET_PARAM_ST", "AtkParam_Pc": "ATK_PARAM_ST", "SpEffectParam": "SP_EFFECT_PARAM_ST",
         "AssetEnvironmentGeometryParam": "ASSET_GEOMETORY_PARAM_ST"}
KIND = {"s8": "S8", "u8": "U8", "s16": "S16", "u16": "U16", "s32": "S32", "u32": "U32", "f32": "F32"}


def wanted():
    cfg, weapons = br.load_inputs()
    plan = br.make_plan(cfg, weapons)
    out = {s: set() for s in TYPES}
    for stem, rows in plan["rows"].items():
        for _rid, _name, ov, _clone in rows:
            out[stem] |= set(ov)
    for stem, d in br.SAFETY.items():
        out[stem] |= set(d)
    for key, d in br.SAFETY_M6.items():
        out["Bullet" if key.endswith("_bullet") else "AtkParam_Pc"] |= set(d)
    for key, d in br.SAFETY_M7.items():
        out["SpEffectParam" if key == "speffect" else "Bullet" if key.endswith("_bullet") else "AtkParam_Pc"] |= set(d)
    for key, d in br.SAFETY_C3.items():
        out["SpEffectParam" if key == "marker_sp" else "Bullet"] |= set(d)
    out["Bullet"] |= {"hitRadius", "HitBulletID", "sfxId_Hit", "sfxId_Flick", "sfxPostureType", "atkId_Bullet"}
    out["AtkParam_Pc"] |= {"atkObj", "isEnableCalcDamageForBushesObj", "spEffectId0", "atkPhys"}
    out["SpEffectParam"] |= {"effectEndurance", "vfxId", "isDisableNetSync"}
    out["AssetEnvironmentGeometryParam"] |= {"hp", "defense", "isBushesForDamage"}
    return out


def generate():
    lines = [
        "// @generated by tools/scripts/gen_regbuild_fields.py from the Paramdex ER defs at regulation 11730034.",
        "// Facts only (field name, type, byte offset, bit offset/width); do not edit by hand.",
        "",
        "use crate::fields::{Field, Kind, ParamLayout};",
        "",
    ]
    consts = []
    for stem, fields in wanted().items():
        ptype = TYPES[stem]
        _fn, layout, size = param_rows.load_def(param_rows.DEFAULT_DEFS, ptype, br.REGULATION_VERSION)
        by = {x[0]: x for x in layout}
        missing = sorted(f for f in fields if f not in by)
        if missing:
            raise SystemExit(f"{stem}: fields not in the def: {missing}")
        rows = []
        for name in sorted(fields, key=lambda f: (by[f][2], by[f][3] or 0)):
            _n, typ, off, boff, bits, cnt = by[name]
            if cnt != 1 or typ not in KIND:
                raise SystemExit(f"{stem}.{name}: unsupported type {typ}[{cnt}]")
            if boff is None:
                rows.append(f'    Field {{ name: "{name}", kind: Kind::{KIND[typ]}, offset: {off}, bit: None }},')
            else:
                rows.append(f'    Field {{ name: "{name}", kind: Kind::{KIND[typ]}, offset: {off}, bit: Some(({boff}, {bits})) }},')
        cname = stem.upper()
        consts.append(cname)
        lines.append(f"pub const {cname}: ParamLayout = ParamLayout {{")
        lines.append(f'    stem: "{stem}",')
        lines.append(f'    param_type: "{ptype}",')
        lines.append(f"    row_size: {size},")
        lines.append("    fields: &[")
        lines += ["    " + r for r in rows]
        lines.append("    ],")
        lines.append("};")
        lines.append("")
    lines.append("pub const ALL: &[&ParamLayout] = &[" + ", ".join(f"&{c}" for c in consts) + "];")
    return "\n".join(lines) + "\n"


def main(argv):
    text = generate()
    if argv == ["--check"]:
        same = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print(f"{OUT}: {'up to date' if same else 'DIFFERS from a fresh generation'}")
        return 0 if same else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
